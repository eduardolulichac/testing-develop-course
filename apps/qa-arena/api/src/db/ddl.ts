/** Meta schema (shared by all sessions): only a registry of sessions, no business data. */
export const META_DDL = `
CREATE SCHEMA IF NOT EXISTS arena_meta;
CREATE TABLE IF NOT EXISTS arena_meta.sessions (
  id text PRIMARY KEY,
  schema_name text NOT NULL UNIQUE,
  scenario text NOT NULL DEFAULT 'baseline',
  settings jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_seen timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE arena_meta.sessions ADD COLUMN IF NOT EXISTS release text;
ALTER TABLE arena_meta.sessions ADD COLUMN IF NOT EXISTS rng_seed integer;
ALTER TABLE arena_meta.sessions ADD COLUMN IF NOT EXISTS owner_ip_hash text;
CREATE INDEX IF NOT EXISTS sessions_owner_last_seen ON arena_meta.sessions (owner_ip_hash, last_seen);
CREATE TABLE IF NOT EXISTS arena_meta.fault_counters (
  session_id text NOT NULL REFERENCES arena_meta.sessions (id) ON DELETE CASCADE,
  point text NOT NULL,
  n integer NOT NULL DEFAULT 0,
  PRIMARY KEY (session_id, point)
);
`;

/** Business schema, created once per session inside its own Postgres schema. */
export const SESSION_DDL = `
CREATE TABLE users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE,
  name text NOT NULL,
  password_hash text NOT NULL,
  role text NOT NULL CHECK (role IN ('customer','admin')),
  created_at timestamptz NOT NULL
);
CREATE TABLE tokens (
  token_hash text PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL
);
CREATE TABLE products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku text NOT NULL UNIQUE,
  name text NOT NULL,
  description text NOT NULL,
  price_cents integer NOT NULL CHECK (price_cents >= 0),
  category text NOT NULL,
  active boolean NOT NULL DEFAULT true
);
CREATE TABLE inventory (
  product_id integer PRIMARY KEY REFERENCES products(id) ON DELETE CASCADE,
  stock integer NOT NULL CHECK (stock >= 0)
);
CREATE TABLE carts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  coupon_code text,
  coupon_stack integer NOT NULL DEFAULT 0,
  coupon_applied_at timestamptz
);
CREATE TABLE cart_items (
  cart_id integer NOT NULL REFERENCES carts(id) ON DELETE CASCADE,
  product_id integer NOT NULL REFERENCES products(id),
  quantity integer NOT NULL CHECK (quantity >= 1), -- the cap of 10 is a domain rule (cart.quantity_limit_ignored can lift it)
  PRIMARY KEY (cart_id, product_id)
);
CREATE TABLE coupons (
  code text PRIMARY KEY,
  type text NOT NULL CHECK (type IN ('percent','fixed')),
  value integer NOT NULL CHECK (value > 0),
  min_subtotal_cents integer NOT NULL DEFAULT 0,
  max_uses integer,
  used_count integer NOT NULL DEFAULT 0,
  expires_at timestamptz,
  active boolean NOT NULL DEFAULT true
);
CREATE TABLE orders (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id),
  status text NOT NULL CHECK (status IN ('pending','paid','shipped','cancelled','payment_failed')),
  subtotal_cents integer NOT NULL,
  discount_cents integer NOT NULL,
  shipping_cents integer NOT NULL,
  total_cents integer NOT NULL,
  coupon_code text,
  shipping_address text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE order_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id integer NOT NULL REFERENCES products(id),
  name text NOT NULL,
  unit_price_cents integer NOT NULL,
  quantity integer NOT NULL
);
CREATE TABLE coupon_redemptions (
  coupon_code text NOT NULL REFERENCES coupons(code),
  user_id integer NOT NULL REFERENCES users(id),
  order_id integer NOT NULL REFERENCES orders(id),
  PRIMARY KEY (coupon_code, user_id)
);
CREATE TABLE payments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders(id),
  amount_cents integer NOT NULL,
  status text NOT NULL CHECK (status IN ('approved','declined')),
  card_last4 text NOT NULL,
  reason text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE notifications (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type text NOT NULL,
  message text NOT NULL,
  read boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE arena_counters (
  point text PRIMARY KEY,
  n integer NOT NULL
);
`;
